    [HarmonyPatch(
    typeof(CraftingUIController),
    "AddIngredient",
    new Type[]
    {
        typeof(Item),
        typeof(int),
        typeof(int),
        typeof(bool)
    }
)]
    internal static class CraftingUIControllerAddIngredientAPMerchantPatch
    {
        private sealed class State
        {
            public bool IsAPResult;
            public int ChildCountBefore;
            public MerchantAPDisplay? Display;
        }

        [HarmonyPrefix]
        private static void Prefix(
            CraftingUIController __instance,
            Item item,
            out State __state)
        {
            __state = new State();

            try
            {
                if (!MerchantPresentation.TryConsumeResultIngredient(
                        item,
                        out MerchantAPDisplay? display) ||
                    display == null)
                {
                    return;
                }

                __state.IsAPResult = true;
                __state.Display = display;

                GameObject content =
                    __instance.craftingRequirementsScrollContent;

                if (content != null)
                {
                    __state.ChildCountBefore =
                        content.transform.childCount;
                }

                Plugin.LogSource.LogInfo(
                    $"[AP SHOP UI] Captured result ingredient: " +
                    $"{item.GetTitle()} -> {display.APItemName}"
                );
            }
            catch (Exception ex)
            {
                Plugin.LogSource.LogError(
                    $"[AP SHOP UI] AddIngredient prefix failed: {ex}"
                );
            }
        }

        [HarmonyPostfix]
        private static void Postfix(
            CraftingUIController __instance,
            Item item,
            State __state)
        {
            try
            {
                if (__state == null ||
                    !__state.IsAPResult ||
                    __state.Display == null)
                {
                    return;
                }

                GameObject content =
                    __instance.craftingRequirementsScrollContent;

                if (content == null)
                    return;

                Transform parent = content.transform;

                if (parent.childCount <= __state.ChildCountBefore)
                {
                    Plugin.LogSource.LogWarning(
                        "[AP SHOP UI] AddIngredient created no detectable child."
                    );
                    return;
                }

                // AddIngredient appends the newly instantiated ingredient row.
                Transform row =
                    parent.GetChild(parent.childCount - 1);

                ApplyAPResultPresentation(
                    row,
                    __state.Display
                );
            }
            catch (Exception ex)
            {
                Plugin.LogSource.LogError(
                    $"[AP SHOP UI] AddIngredient postfix failed: {ex}"
                );
            }
        }

        private static void ApplyAPResultPresentation(
            Transform row,
            MerchantAPDisplay display)
        {
            string desiredTitle =
                string.IsNullOrWhiteSpace(display.PlayerName)
                    ? display.APItemName
                    : $"{display.APItemName} ({display.PlayerName})";

            // ----- TEXT -----

            TMP_Text[] texts =
                row.GetComponentsInChildren<TMP_Text>(true);

            TMP_Text? titleText = null;

            foreach (TMP_Text text in texts)
            {
                if (text == null)
                    continue;

                string current =
                    text.text ?? string.Empty;

                Plugin.LogSource.LogInfo(
                    $"[AP SHOP UI] Result-row text: " +
                    $"'{text.gameObject.name}' = '{current}'"
                );

                // Quantity / "Have" labels should not be touched.
                // The actual item-name field is the non-numeric text
                // which isn't a Have label.
                if (string.IsNullOrWhiteSpace(current))
                    continue;

                if (current.StartsWith("Have"))
                    continue;

                if (int.TryParse(current, out _))
                    continue;

                titleText = text;
            }

            if (titleText != null)
            {
                Plugin.LogSource.LogInfo(
                    $"[AP SHOP UI] Result title: " +
                    $"'{titleText.text}' -> '{desiredTitle}'"
                );

                titleText.text = desiredTitle;
            }
            else
            {
                Plugin.LogSource.LogWarning(
                    "[AP SHOP UI] Could not identify result title TMP_Text."
                );
            }

            // ----- ICON -----

            RawImage[] images =
                row.GetComponentsInChildren<RawImage>(true);

            Texture2D? logo =
                ArchipelagoNotifications.GetLogoTexture();

            if (logo == null)
            {
                Plugin.LogSource.LogWarning(
                    "[AP SHOP UI] AP logo unavailable for result row."
                );
                return;
            }

            foreach (RawImage image in images)
            {
                if (image == null)
                    continue;

                Texture currentTexture =
                    image.texture;

                Plugin.LogSource.LogInfo(
                    $"[AP SHOP UI] Result-row RawImage: " +
                    $"'{image.gameObject.name}' / " +
                    $"texture={currentTexture?.name ?? "NULL"}"
                );

                // Do not blindly replace decorative empty RawImages.
                // The vanilla item icon is the populated texture.
                if (currentTexture == null)
                    continue;

                image.texture = logo;

                Plugin.LogSource.LogInfo(
                    $"[AP SHOP UI] Result icon: " +
                    $"{currentTexture.name} -> {logo.name}"
                );

                break;
            }
        }
    }


