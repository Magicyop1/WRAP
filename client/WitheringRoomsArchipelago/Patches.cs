    [HarmonyPatch(
    typeof(CraftingUIController),
    "RefreshStore"
)]
    internal static class CraftingUIControllerRefreshStorePatch
    {
        private sealed class RefreshState
        {
            public Il2CppSystem.Collections.Generic.List<CraftingCombination>?
                OriginalCombinations;

            public bool MerchantOwnershipOverrideActive;
        }

        [HarmonyPrefix]
        private static void Prefix(
            CraftingUIController __instance,
            out RefreshState? __state)
        {
            __state = null;

            try
            {
                CraftingSet set = __instance.craftingSet;

                if (set == null ||
                    set.combinations == null)
                {
                    return;
                }

                MerchantRandomizer.BeginRefreshStore();

                var original = set.combinations;

                var filtered =
                    new Il2CppSystem.Collections.Generic.List<
                        CraftingCombination>();

                int kept = 0;
                int removed = 0;

                for (int i = 0; i < original.Count; i++)
                {
                    CraftingCombination combo = original[i];

                    if (combo == null)
                        continue;

                    bool hide = false;

                    if (MerchantRandomizer.TryGetMerchantLocation(
                            combo,
                            out RandomizedItemData? data) &&
                        data != null &&
                        data.LocationId.HasValue)
                    {
                        MerchantPresentation.RegisterActiveMerchantItemGuid(
                            data.Guid
                        );

                        bool checkedByAP =
                            ArchipelagoClient.IsLocationChecked(
                                data.LocationId.Value
                            );

                        Plugin.LogSource.LogInfo(
                            $"[AP SHOP FILTER] " +
                            $"{data.Name} -> " +
                            $"{data.LocationName} / " +
                            $"checked={checkedByAP}"
                        );

                        if (checkedByAP)
                        {
                            hide = true;
                            removed++;

                            Plugin.LogSource.LogInfo(
                                $"[AP SHOP FILTER] Hiding sold item: " +
                                $"{data.Name} / " +
                                $"{data.LocationName}"
                            );
                        }
                        if (!checkedByAP)
                        {
                            MerchantRandomizer.RegisterUncheckedMerchantItem(
                                data
                            );
                        }
                    }

                    if (!hide)
                    {
                        filtered.Add(combo);
                        kept++;
                    }
                }

                __state = new RefreshState
                {
                    OriginalCombinations = original,
                    MerchantOwnershipOverrideActive = true
                };

                set.combinations = filtered;

                Plugin.LogSource.LogInfo(
                    $"[AP SHOP FILTER] RefreshStore input: " +
                    $"{original.Count} original, " +
                    $"{kept} visible, " +
                    $"{removed} AP-checked."
                );
            }
            catch (Exception ex)
            {
                Plugin.LogSource.LogError(
                    $"[AP SHOP FILTER] Prefix failed: {ex}"
                );
            }
        }

        [HarmonyFinalizer]
        private static Exception? Finalizer(
            CraftingUIController __instance,
            RefreshState? __state,
            Exception? __exception)
        {
            try
            {
                if (__state?.OriginalCombinations != null &&
                    __instance != null &&
                    __instance.craftingSet != null)
                {
                    __instance.craftingSet.combinations =
                        __state.OriginalCombinations;

                    Plugin.LogSource.LogInfo(
                        "[AP SHOP FILTER] Restored original " +
                        "CraftingSet combinations."
                    );
                }
            }
            catch (Exception ex)
            {
                Plugin.LogSource.LogError(
                    $"[AP SHOP FILTER] Failed restoring " +
                    $"CraftingSet: {ex}"
                );
            }
            finally
            {
                if (__state?.MerchantOwnershipOverrideActive == true)
                {
                    MerchantRandomizer.EndRefreshStore();
                }
            }

            // Preserve any exception from the original method.
            return __exception;
        }
    }

