    [HarmonyPatch(
    typeof(Inventory),
    nameof(Inventory.NewItem),
    new Type[]
    {
        typeof(Item),
        typeof(LocalizedString),
        typeof(bool),
        typeof(bool),
        typeof(bool),
        typeof(MansionSimulationObject),
        typeof(int)
    }
)]
    public static class InventoryNewItemPatch
    {
        [HarmonyPrefix]
        public static bool Prefix(
            ref Item inNewItem,
            LocalizedString source,
            bool select,
            bool ressurected,
            bool disableGoldScale,
            MansionSimulationObject sourceObject,
            int quantity)
        {
            ItemCatalog.RecordItem(inNewItem);

            if (ItemRandomizer.TryConsumeLinkedSecondarySuppression(
        inNewItem,
        quantity))
            {
                /*
                 * This is the automatic headpiece generated by an
                 * AP-delivered outfit.
                 *
                 * Skip Inventory.NewItem completely:
                 *
                 * - no physical secondary item,
                 * - no natural AP discovery,
                 * - no later AddItem.
                 */
                return false;
            }



            if (ItemRandomizer.IsInternalGameStateItem(inNewItem))
            {
                Plugin.LogSource.LogInfo(
                    $"[AP INTERNAL STATE] NewItem allowing unchanged: " +
                    $"{inNewItem.GetTitle()} x{quantity}"
                );

                ItemRandomizer.ExpectAddItemFromNewItem(
                    inNewItem,
                    quantity
                );

                return true;
            }

            bool recoverySourceHasComponent = false;

            if (CursedChestRecoveryGuard.IsRecoveryAcquisition(
                    ressurected,
                    sourceObject,
                    out recoverySourceHasComponent))
            {
                Plugin.LogSource.LogInfo(
                    $"[AP RECOVERY CHEST] " +
                    $"Allowing recovered item unchanged: " +
                    $"{inNewItem?.GetTitle() ?? "NULL"} x{quantity} " +
                    $"ressurected={ressurected} " +
                    $"resurrectableSource={recoverySourceHasComponent}"
                );

                /*
                 * A recovery chest is restoring an item lost on a prior night.
                 * It is NOT the item's canonical vanilla source.
                 *
                 * Therefore:
                 *   - allow the real item into physical inventory,
                 *   - do NOT call ProcessNaturalItem(),
                 *   - do NOT send Discover <item>,
                 *   - do NOT record an unresolved-region census row.
                 *
                 * NewItem normally produces a later AddItem call. Register it
                 * here so InventoryAddItemPatch consumes that second stage
                 * instead of reinterpreting it as a direct natural discovery.
                 */
                ItemRandomizer.ExpectAddItemFromNewItem(
                    inNewItem,
                    quantity
                );

                return true;
            }


            // =============================================================
            // TEMPORARY AP TREASURE-REROLL DIAGNOSTIC
            // =============================================================
            try
                {
                Plugin.LogSource.LogInfo(
                    $"[AP TREASURE TRACE] NewItem: " +
                    $"item={inNewItem?.GetTitle() ?? "NULL"}, " +
                    $"sourceObject={(sourceObject != null ? "YES" : "NULL")}"
                );

                if (sourceObject != null)
                {
                    Plugin.LogSource.LogInfo(
                        $"[AP TREASURE TRACE] sourceObject runtime type=" +
                        $"{sourceObject.GetType().FullName}"
                    );

                    Plugin.LogSource.LogInfo(
                        $"[AP TREASURE TRACE] sourceObject pointer=" +
                        $"0x{sourceObject.Pointer.ToInt64():X}"
                    );
                }
            }
            catch (Exception ex)
            {
                Plugin.LogSource.LogError(
                    $"[AP TREASURE TRACE] Diagnostic failed: {ex}"
                );
            }
            // =============================================================
            // TEMPORARY AP TREASURE SOURCE COMPONENT DIAGNOSTIC
            // =============================================================
            try
            {
                if (sourceObject != null)
                {
                    Plugin.LogSource.LogInfo(
                        "[AP TREASURE TRACE] Probing sourceObject treasure components..."
                    );

                    SimulationTreasureComponent treasureComponent =
                        sourceObject.GetComponent<SimulationTreasureComponent>();

                    SimulationLoreTreasureComponent loreTreasureComponent =
                        sourceObject.GetComponent<SimulationLoreTreasureComponent>();

                    Plugin.LogSource.LogInfo(
                        $"[AP TREASURE TRACE] SimulationTreasureComponent=" +
                        $"{(treasureComponent != null ? "YES" : "NO")}"
                    );

                    Plugin.LogSource.LogInfo(
                        $"[AP TREASURE TRACE] SimulationLoreTreasureComponent=" +
                        $"{(loreTreasureComponent != null ? "YES" : "NO")}"
                    );

                    Plugin.LogSource.LogInfo(
                        $"[AP TREASURE TRACE] sourceObject runtime type=" +
                        $"{sourceObject.GetType().FullName}"
                    );
                }
            }
            catch (Exception ex)
            {
                Plugin.LogSource.LogError(
                    $"[AP TREASURE TRACE] Component probe failed: {ex}"
                );
            }


            if (ItemRandomizer.BypassRandomizer)
            {
                // This is an AP/internal grant. NewItem is allowed,
                // but its eventual AddItem must NOT become a check.
                ItemRandomizer.ExpectAddItemFromNewItem(
                    inNewItem,
                    quantity
                );

                ItemRandomizer.ExpectInternalAddItemFromNewItem(
                    inNewItem,
                    quantity
                );

                return true;
            }

            bool allowOriginal =
                ItemRandomizer.ProcessNaturalItem(
                    ref inNewItem,
                    quantity,
                    sourceObject
                );

            if (allowOriginal)
            {
                // ProcessNaturalItem may have replaced the item with
                // filler, so register the FINAL item reference.
                ItemRandomizer.ExpectAddItemFromNewItem(
                    inNewItem,
                    quantity
                );
            }

            return allowOriginal;
        }
    }


    [HarmonyPatch(
    typeof(Inventory),
    nameof(Inventory.AddItem),
    new Type[]
    {
        typeof(Item),
        typeof(int),
        typeof(Inventory.ReportItemTelemetry),
        typeof(Inventory.QueuedNewItem)
    }
)]
    public static class InventoryAddItemPatch
    {
        [HarmonyPrefix]
        public static bool Prefix(
            ref Item item,
            int count)
        {
            ItemCatalog.RecordItem(item);

            // Most importantly, test this BEFORE deciding that
            // AddItem represents a new natural acquisition.
            if (ItemRandomizer.ConsumeExpectedAddItem(
        item,
        count))
            {
                bool cameFromAPInternalGrant =
                    ItemRandomizer.ConsumeExpectedInternalAddItem(
                        item,
                        count
                    );

                if (cameFromAPInternalGrant)
                {
                    /*
                     * Arm the exact secondary suppression immediately before
                     * vanilla handles the primary AddItem.
                     *
                     * If this item isn't one of the five primaries,
                     * ArmLinkedSecondarySuppression() is simply a no-op.
                     */
                    ItemRandomizer.ArmLinkedSecondarySuppression(
                        item,
                        count
                    );
                }

                return true;
            }

            // Retain this as an additional safety net for any
            // synchronous internal AddItem calls.
            if (ItemRandomizer.BypassRandomizer)
                return true;

            Plugin.LogSource.LogInfo(
                $"[AP ADD ITEM] Direct AddItem acquisition: " +
                $"{item?.GetTitle() ?? "NULL"} x{count}"
            );

            if (ItemRandomizer.IsInternalGameStateItem(item))
            {
                Plugin.LogSource.LogInfo(
                    $"[AP INTERNAL STATE] Allowing unchanged: " +
                    $"{item.GetTitle()} x{count}"
                );

                return true;
            }

            return ItemRandomizer.ProcessNaturalItem(
                ref item,
                count
            );
        }

        
    }



