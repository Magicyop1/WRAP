                    merchantTexture;

                MerchantSelectedItemPresentation.Pending =
                    null;
            }
            catch (Exception ex)
            {
                Plugin.LogSource.LogError(
                    $"[AP ICON CALLBACK] Exception: {ex}"
                );

                MerchantSelectedItemPresentation.Pending =
                    null;
            }
        }
