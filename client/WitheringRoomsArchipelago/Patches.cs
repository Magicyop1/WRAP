    // =====================================================================
    // AP MERCHANT STOCK AUTHORITY
    // =====================================================================
    //
    // Vanilla merchant stock can become zero because the vanilla result item
    // has already been obtained, a stock counter has been consumed, etc.
    //
    // For an Archipelago-randomized PURCHASE location, that vanilla stock
    // bookkeeping is no longer authoritative.
    //
    // AP checked-location state is the authority:
    //
    //     AP unchecked -> must remain in stock
    //     AP checked   -> existing RefreshStore filter hides the row
    //
    // We patch GetStock rather than CanCraft so vanilla currency/ingredient
    // requirements remain completely intact.
    //
    [HarmonyPatch(
        typeof(CraftingCombination),
        nameof(CraftingCombination.GetStock)
    )]
    internal static class CraftingCombination_GetStock_APMerchant_Patch
    {
        [HarmonyPostfix]
        private static void Postfix(
            CraftingCombination __instance,
            ref int __result)
        {
            try
            {
                if (__instance == null)
                    return;

                // Do not touch ordinary positive vanilla stock.
                if (__result > 0)
                    return;

                if (!ArchipelagoClient.Connected)
                    return;

                /*
                 * IMPORTANT:
                 *
                 * TryGetMerchantLocation() is now Purchase-only from the
                 * previous sell-menu fix. Therefore Craft and Sell rows cannot
                 * enter this branch.
                 */
                if (!MerchantRandomizer.TryGetMerchantLocation(
                        __instance,
                        out RandomizedItemData? data) ||
                    data == null ||
                    !data.LocationId.HasValue)
                {
                    return;
                }

                long locationId =
                    data.LocationId.Value;

                /*
                 * If AP already has the location checked, leave vanilla stock
                 * alone. The existing RefreshStore patch will remove that
                 * combination from the visible merchant stock anyway.
                 */
                if (ArchipelagoClient.IsLocationChecked(
                        locationId))
                {
                    return;
                }

                /*
                 * The AP merchant location is still outstanding.
                 *
                 * Regardless of why vanilla believes its stock is exhausted,
                 * expose one purchasable copy. We deliberately do NOT alter
                 * CanCraft(), so costs/ingredients still have to be satisfied.
                 */
                Plugin.LogSource.LogInfo(
                    $"[AP SHOP STOCK] Forcing stock available: " +
                    $"{data.Name} / {data.LocationName} " +
                    $"(vanilla stock={__result}, AP unchecked)"
                );

                __result = 1;
            }
            catch (Exception ex)
            {
                Plugin.LogSource.LogError(
                    $"[AP SHOP STOCK] GetStock postfix failed: {ex}"
                );
            }
        }
    }

