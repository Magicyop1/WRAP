    // =====================================================================
    // AP QUEST / DIALOG ITEM-CONDITION COMPATIBILITY
    //
    // Vanilla dialogue frequently uses:
    //
    //     DialogCommentNode.ScoreItem(item, ItemStatus)
    //
    // to ask whether a world item has been acquired.
    //
    // For randomized items, natural acquisition instead sends that item's
    // AP location check and suppresses the physical vanilla copy.
    //
    // Therefore, for ItemStatus.Has ONLY, replace vanilla possession with
    // "the vanilla AP location has been checked".
    //
    // Do NOT patch Inventory.HasItem globally. Doors, crafting, consumption,
    // equipment, etc. must continue to require actual possession.
    // =====================================================================

    [HarmonyPatch(
        typeof(DialogCommentNode),
        nameof(DialogCommentNode.ScoreItem),
        new Type[]
        {
        typeof(Item),
        typeof(ItemStatus)
        }
    )]
    internal static class DialogCommentNode_ScoreItem_APQuestCompat_Patch
    {
        [HarmonyPrefix]
        private static bool Prefix(
            Item item,
            ItemStatus status,
            ref float __result)
        {
            try
            {
                // Preserve completely vanilla behavior outside an
                // active Archipelago session.
                if (!ArchipelagoClient.Connected)
                    return true;

                // First conservative implementation:
                //
                // Only reinterpret the literal vanilla "Has" condition.
                // Completed / NotCompleted / DoesNotHave / etc. retain
                // their original semantics.
                if (status != ItemStatus.Has)
                    return true;

                if (item == null)
                    return true;

                RandomizedItemData? data =
                    ItemData.ByGuid(item.GetGUID());

                // Non-randomized items retain vanilla ScoreItem behavior.
                if (data == null ||
                    !data.CreatesLocation ||
                    !data.LocationId.HasValue)
                {
                    return true;
                }

                bool checkedLocation =
                    ItemRandomizer
                        .ShouldSatisfyVanillaHasCondition(item);

                // We are deliberately OVERRIDING vanilla evaluation here,
                // rather than merely turning failures into successes.
                //
                // This distinction matters:
                //
                //   AP sent item, vanilla location NOT checked
                //       -> false
                //
                //   vanilla location checked, physical item suppressed
                //       -> true
                //
                // Thus narrative progression follows vanilla-world
                // acquisition, while physical inventory remains controlled
                // by AP receipt.
                __result = checkedLocation ? 1.0f : 0.0f;

                Plugin.LogSource.LogInfo(
                    $"[AP QUEST COMPAT] " +
                    $"ScoreItem Has override: " +
                    $"{item.GetTitle()} ({item.GetGUID()}) -> " +
                    $"locationChecked={checkedLocation}"
                );

                // Skip vanilla ScoreItem().
                return false;
            }
            catch (Exception ex)
            {
                Plugin.LogSource.LogError(
                    $"[AP QUEST COMPAT] ScoreItem patch failed: {ex}"
                );

                // Fail safely back to vanilla behavior.
                return true;
            }
        }
    }





